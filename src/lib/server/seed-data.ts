const now = new Date();

function hoursAgo(hours: number) {
  return new Date(now.getTime() - hours * 3_600_000);
}

function makeReport(index: number, route: Route, unit: string | null, problems: Problem[], hours: number): Report {
  return {
    id: `seed-${index}`,
    route,
    unit,
    problems,
    createdAt: hoursAgo(hours),
    hiddenAt: null,
  };
}

